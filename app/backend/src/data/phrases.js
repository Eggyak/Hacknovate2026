/**
 * Look up a phrase. Falls back to English for any language that lacks a key,
 * which is visible in the UI rather than silently empty.
 */
export function t(key, lang = 'en', vars = {}) {
  const entry = PHRASES[key];
  if (!entry) return key;
  let s = entry[lang] || entry.en || key;
  for (const [k, v] of Object.entries(vars)) {
    s = s.split(`{${k}}`).join(String(v));
  }
  return s;
}

/** Keys missing a translation, so gaps are findable in CI rather than in production. */
export function missingTranslations(languageCodes) {
  const gaps = [];
  for (const [key, entry] of Object.entries(PHRASES)) {
    for (const code of languageCodes) {
      if (!entry[code]) gaps.push(`${key}.${code}`);
    }
  }
  return gaps;
}
